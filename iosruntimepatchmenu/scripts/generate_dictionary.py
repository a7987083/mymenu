#!/usr/bin/env python3
"""Deterministic P4 offline dictionary compiler. No network or runtime files."""
import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "resources" / "MethodTranslation.zh-CN.json"
OUTPUT = ROOT / "src" / "ZNMethodDictionary.generated.h"
TOKEN = "ZNMP4"

def parse_pairs(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON key: {key}")
        result[key] = value
    return result

def compile_header():
    doc = json.loads(SOURCE.read_text(encoding="utf-8"), object_pairs_hook=parse_pairs)
    words = doc["entries"]
    if doc.get("schemaVersion") != 1 or doc.get("entryCount") != 3000 or len(words) != 3000:
        raise ValueError(f"dictionary must contain exactly 3000 unique terms: {len(words)}")
    for key, value in words.items():
        if not re.fullmatch(r"[a-z][a-z0-9]*", key):
            raise ValueError(f"invalid dictionary key: {key!r}")
        if not isinstance(value, str) or not value.strip() or len(value) > 40:
            raise ValueError(f"invalid translation: {key!r}")
    stable = {key: words[key] for key in sorted(words)}
    body = json.dumps(stable, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    if f"){TOKEN}\"" in body:
        raise ValueError("raw literal delimiter collision")
    return (
        "// AUTOGENERATED by scripts/generate_dictionary.py; DO NOT EDIT.\n"
        "// Source: resources/MethodTranslation.zh-CN.json (3000 entries)\n"
        "#pragma once\n"
        "#define ZNM_P4_DICTIONARY_COUNT 3000\n"
        f"static const char kZNMethodDictionaryJSON[] = R\"{TOKEN}({body}){TOKEN}\";\n"
    )

def main():
    arg = argparse.ArgumentParser()
    arg.add_argument("--check", action="store_true")
    opts = arg.parse_args()
    text = compile_header()
    if opts.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print("P4 dictionary header missing/stale; run generate_dictionary.py", file=sys.stderr)
            return 1
        print("P4 offline dictionary OK: exactly 3000 unique terms, header synchronized")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Generated {OUTPUT}: 3000 unique words")
    return 0

if __name__ == "__main__":
    sys.exit(main())
